#!/usr/bin/env python3
"""Build a curated, reproducible static publication folder, never upload Deliverables wholesale."""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit, unquote
import hashlib
import json
import shutil

ROOT=Path(__file__).resolve().parent.parent
DEST=ROOT/'publish'
PAGES=['index.html','theogony-reader.html','translation.html','translation-records.html','imprint.html','privacy.html','reuse.html','translation-and-legal.html']
class References(HTMLParser):
    def __init__(self):super().__init__();self.refs=[];self.ids=set();self.fragment_links=[]
    def handle_starttag(self,tag,attrs):
        attrs=dict(attrs)
        if 'id' in attrs:
            assert attrs['id'] not in self.ids,attrs['id']
            self.ids.add(attrs['id'])
        for key in ('href','src'):
            if attrs.get(key):self.refs.append(attrs[key])

def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()

def package():
    files=set(PAGES+['LICENSE-CONTENT.md','LICENSE','NOTICE.md','sources/perseus-license.md','robots.txt','sitemap.xml','favicon.ico','assets/theogony-share.jpg','data/theogony.json','data/theogony.schema.json'])
    queue=list(PAGES);parsed={}
    while queue:
        relative=queue.pop()
        path=ROOT/relative
        assert path.is_file(),relative
        if path.suffix!='.html':continue
        parser=References();parser.feed(path.read_text());parsed[relative]=parser
        for ref in parser.refs:
            url=urlsplit(ref)
            if url.scheme or url.netloc:continue
            target=Path(relative).parent/unquote(url.path) if url.path else Path(relative)
            assert '..' not in target.parts,ref
            assert (ROOT/target).is_file(),(relative,ref)
            if target.as_posix() not in files:
                files.add(target.as_posix());queue.append(target.as_posix())
    # Include the exact accepted output for each linked run record, preserving hashes.
    for relative in list(files):
        if relative.endswith('.metrics.json'):
            metrics=json.loads((ROOT/relative).read_text())
            output=relative.removesuffix('.metrics.json')+'.json'
            prompt=relative.removesuffix('.metrics.json')+'.prompt.txt'
            assert digest(ROOT/output)==metrics['output_sha256'],output
            assert digest(ROOT/prompt)==metrics['prompt_sha256'],prompt
            files.update([output,prompt])
    # Validate all internal fragment links after the complete page inventory is known.
    for relative,parser in parsed.items():
        for ref in parser.refs:
            url=urlsplit(ref)
            if url.scheme or url.netloc or not url.fragment:continue
            target=(Path(relative).parent/unquote(url.path)).as_posix() if url.path else relative
            if target in parsed:assert unquote(url.fragment) in parsed[target].ids,(relative,ref)
    assert not any(Path(p).name.startswith('.') for p in files)
    DEST.mkdir(exist_ok=True)
    old=set()
    manifest_path=DEST/'publication-manifest.json'
    if manifest_path.exists():old=set(json.loads(manifest_path.read_text())['files'])
    for relative in sorted(files):
        dest=DEST/relative;dest.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(ROOT/relative,dest)
    # Remove only files generated by a previous manifest, never local Vercel account state.
    for relative in old-files:
        (DEST/relative).unlink(missing_ok=True)
    config={'$schema':'https://openapi.vercel.sh/vercel.json','framework':None,'buildCommand':None,'outputDirectory':'.','cleanUrls':False,'headers':[{'source':'/data/(.*)','headers':[{'key':'Access-Control-Allow-Origin','value':'*'},{'key':'X-Robots-Tag','value':'noindex, follow'}]},{'source':'/pipeline/(.*)','headers':[{'key':'X-Robots-Tag','value':'noindex, follow'}]},{'source':'/sources/(.*)','headers':[{'key':'X-Robots-Tag','value':'noindex, follow'}]},{'source':'/publication-manifest.json','headers':[{'key':'X-Robots-Tag','value':'noindex, follow'}]},{'source':'/(.*)','headers':[{'key':'X-Content-Type-Options','value':'nosniff'},{'key':'Referrer-Policy','value':'strict-origin-when-cross-origin'},{'key':'X-Frame-Options','value':'DENY'}]},{'source':'/assets/optimized/(.*)','headers':[{'key':'Cache-Control','value':'public, max-age=31536000, immutable'}]}]}
    (DEST/'vercel.json').write_text(json.dumps(config,indent=2)+'\n')
    (DEST/'.vercelignore').write_text('.vercel\n.git\n.gitignore\n.env*\n.DS_Store\n')
    manifest={'files':{p:digest(DEST/p) for p in sorted(files)},'total_bytes':sum((DEST/p).stat().st_size for p in files),'note':'Curated static release. Translation outputs and prompts are unchanged tracked records. No CLI credentials, raw session logs, private workspace files or unused previews.'}
    manifest_path.write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Packaged {len(files)} files, {manifest["total_bytes"]/1024/1024:.2f} MiB into {DEST}')

if __name__=='__main__':package()
